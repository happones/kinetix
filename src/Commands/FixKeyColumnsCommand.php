<?php

declare(strict_types=1);

namespace Happones\Kinetix\Commands;

use Happones\Kinetix\Support\HostKeyColumns;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;

/**
 * Writes the migration that converts the `user_id` / `team_id` columns an
 * older install created with the wrong type (see {@see HostKeyColumns}).
 *
 * It writes the migration and does not run it: changing a column's type is
 * worth a look before `migrate`. Only text columns that hold numbers are
 * converted — one holding anything else (a real ULID) is listed, not touched.
 */
class FixKeyColumnsCommand extends Command
{
    /**
     * @var string
     */
    protected $signature = 'kinetix:fix-key-columns {--dry-run : List the columns without writing the migration}';

    /**
     * @var string
     */
    protected $description = 'Write a migration converting Kinetix user_id/team_id columns whose type doesn\'t match the app\'s keys';

    public function handle(): int
    {
        $mismatched = HostKeyColumns::mismatched();

        if ($mismatched === []) {
            $this->components->info('Every Kinetix user_id / team_id column matches the app\'s keys.');

            return self::SUCCESS;
        }

        $convertible = [];

        foreach ($mismatched as $column) {
            $where = "{$column['table']}.{$column['column']} ({$column['actual']}, the {$column['kind']} key is {$column['expected']})";

            if ($column['expected'] !== 'bigint') {
                $this->components->warn("{$where}: holds integers where the key is not — convert it by hand.");

                continue;
            }

            if (! $this->holdsOnlyIntegers($column['table'], $column['column'])) {
                $this->components->warn("{$where}: holds values that aren't numbers — left as it is.");

                continue;
            }

            $this->components->twoColumnDetail($where, 'convert');
            $convertible[] = $column;
        }

        if ($convertible === [] || $this->option('dry-run')) {
            return self::SUCCESS;
        }

        $path = database_path('migrations/'.date('Y_m_d_His').'_fix_kinetix_host_key_columns.php');
        File::ensureDirectoryExists(dirname($path));
        File::put($path, $this->migration($convertible));

        $this->components->info('Wrote '.str_replace(base_path().DIRECTORY_SEPARATOR, '', $path).'. Review it, then run php artisan migrate.');

        return self::SUCCESS;
    }

    /**
     * Whether every non-null value is an integer written as text — what the
     * misdetected columns hold, and what converts without losing anything.
     */
    protected function holdsOnlyIntegers(string $table, string $column): bool
    {
        foreach (DB::table($table)->whereNotNull($column)->select($column)->cursor() as $row) {
            if (! ctype_digit((string) $row->{$column})) {
                return false;
            }
        }

        return true;
    }

    /**
     * @param list<array{table: string, column: string, nullable: bool}> $columns
     */
    protected function migration(array $columns): string
    {
        $postgres = '';
        $schema   = '';

        foreach ($columns as $column) {
            $table = $column['table'];
            $name  = $column['column'];

            $postgres .= "            DB::statement('ALTER TABLE \"{$table}\" ALTER COLUMN \"{$name}\" TYPE bigint USING \"{$name}\"::bigint');\n";
            $schema   .= "        Schema::table('{$table}', function (Blueprint \$table): void {\n"
                ."            \$table->unsignedBigInteger('{$name}')".($column['nullable'] ? '->nullable()' : '')."->change();\n"
                ."        });\n";
        }

        return <<<PHP
<?php

use Illuminate\\Database\\Migrations\\Migration;
use Illuminate\\Database\\Schema\\Blueprint;
use Illuminate\\Support\\Facades\\DB;
use Illuminate\\Support\\Facades\\Schema;

/**
 * Generated by `php artisan kinetix:fix-key-columns`: converts the Kinetix
 * user_id / team_id columns an install before 0.219.15 created as text for
 * an integer-keyed User/Team. They held numbers, so nothing is lost.
 */
return new class extends Migration
{
    public function up(): void
    {
        // PostgreSQL won't cast text to bigint without being told how.
        if (DB::getDriverName() === 'pgsql') {
{$postgres}
            return;
        }

{$schema}    }

    public function down(): void
    {
        // The text type was the mistake; there is nothing to go back to.
    }
};

PHP;
    }
}
